`timescale 1ns/1ps

// AXI-stream clock-domain crossing built from the vendor-supported XPM FIFO.
// TDATA and TLAST cross atomically as one FIFO word.  The FIFO never invents
// or silently discards a transfer: upstream is back-pressured when full and
// downstream sees TVALID only when a complete word is available.
module axis_async_fifo #(
    parameter integer DATA_WIDTH = 32,
    parameter integer FIFO_DEPTH = 1024,
    parameter integer COUNT_WIDTH = $clog2(FIFO_DEPTH) + 1
) (
    input  logic                     s_axis_aclk,
    input  logic                     fifo_reset,
    input  logic [DATA_WIDTH-1:0]    s_axis_tdata,
    input  logic                     s_axis_tvalid,
    output logic                     s_axis_tready,
    input  logic                     s_axis_tlast,

    input  logic                     m_axis_aclk,
    input  logic                     m_axis_reset,
    output logic [DATA_WIDTH-1:0]    m_axis_tdata,
    output logic                     m_axis_tvalid,
    input  logic                     m_axis_tready,
    output logic                     m_axis_tlast,

    output logic [COUNT_WIDTH-1:0]  write_level,
    output logic [COUNT_WIDTH-1:0]  read_level,
    output logic                     almost_full,
    output logic                     write_reset_busy,
    output logic                     read_reset_busy
);

    localparam integer FIFO_WIDTH = DATA_WIDTH + 1;
    localparam integer PROG_FULL_THRESH = FIFO_DEPTH - 16;
    localparam integer PROG_EMPTY_THRESH = 16;

    logic [FIFO_WIDTH-1:0] fifo_din;
    logic [FIFO_WIDTH-1:0] fifo_dout;
    logic fifo_full;
    logic fifo_empty;
    logic fifo_prog_full;
    logic fifo_wr_en;
    logic fifo_rd_en;

    initial begin
        if (FIFO_DEPTH < 32)
            $error("axis_async_fifo FIFO_DEPTH must be at least 32");
        if ((FIFO_DEPTH & (FIFO_DEPTH - 1)) != 0)
            $error("axis_async_fifo FIFO_DEPTH must be a power of two");
    end

    assign fifo_din = {s_axis_tlast, s_axis_tdata};
    assign s_axis_tready = !fifo_full && !write_reset_busy;
    assign fifo_wr_en = s_axis_tvalid && s_axis_tready;

    assign m_axis_tdata = fifo_dout[DATA_WIDTH-1:0];
    assign m_axis_tlast = fifo_dout[DATA_WIDTH];
    // read_reset_busy is generated by XPM in the read clock domain and is the
    // authoritative guard for FIFO output validity.  Do not gate the BRAM read
    // enable with an asynchronously asserted external reset: doing so creates
    // REQP-1839 and can make RAM control timing unanalyzable.
    assign m_axis_tvalid = !fifo_empty && !read_reset_busy;
    assign fifo_rd_en = m_axis_tvalid && m_axis_tready;
    assign almost_full = fifo_prog_full;

    xpm_fifo_async #(
        .CASCADE_HEIGHT(0),
        .CDC_SYNC_STAGES(2),
        .DOUT_RESET_VALUE("0"),
        .ECC_MODE("no_ecc"),
        .EN_SIM_ASSERT_ERR("warning"),
        .FIFO_MEMORY_TYPE("block"),
        .FIFO_READ_LATENCY(0),
        .FIFO_WRITE_DEPTH(FIFO_DEPTH),
        .FULL_RESET_VALUE(0),
        .PROG_EMPTY_THRESH(PROG_EMPTY_THRESH),
        .PROG_FULL_THRESH(PROG_FULL_THRESH),
        .RD_DATA_COUNT_WIDTH(COUNT_WIDTH),
        .READ_DATA_WIDTH(FIFO_WIDTH),
        .READ_MODE("fwft"),
        .RELATED_CLOCKS(0),
        .SIM_ASSERT_CHK(1),
        .USE_ADV_FEATURES("0707"),
        .WAKEUP_TIME(0),
        .WRITE_DATA_WIDTH(FIFO_WIDTH),
        .WR_DATA_COUNT_WIDTH(COUNT_WIDTH)
    ) fifo_i (
        .almost_empty(),
        .almost_full(),
        .dbiterr(),
        .data_valid(),
        .dout(fifo_dout),
        .empty(fifo_empty),
        .full(fifo_full),
        .overflow(),
        .prog_empty(),
        .prog_full(fifo_prog_full),
        .rd_data_count(read_level),
        .rd_rst_busy(read_reset_busy),
        .sbiterr(),
        .underflow(),
        .wr_ack(),
        .wr_data_count(write_level),
        .wr_rst_busy(write_reset_busy),
        .din(fifo_din),
        .injectdbiterr(1'b0),
        .injectsbiterr(1'b0),
        .rd_clk(m_axis_aclk),
        .rd_en(fifo_rd_en),
        .rst(fifo_reset),
        .sleep(1'b0),
        .wr_clk(s_axis_aclk),
        .wr_en(fifo_wr_en)
    );

endmodule
