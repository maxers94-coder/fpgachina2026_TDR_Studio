#include <stddef.h>
#include <stdint.h>

#include "echo_transaction.h"
#include "echo_pl.h"
#include "echo_pl_regs.h"

#define ECHO_EXPECTED_RESULTS 256u
/* An independent polling bound protects against a stopped timer callback. */
#define ECHO_MAX_POLLS 3000000u
#define ECHO_CLEAR_MAX_POLLS 10000u


/*
 * DONE and START_ACCEPTED may still describe the previous acquisition when
 * the second START has not yet taken effect across the AXI/PL boundary.
 * The public wait API preserves the original behavior, while the one-shot
 * echo_run_transaction additionally requires TRANSACTION_COUNT == old + 1.
 * A stale DONE is NOT an error and is NEVER accepted as a new result.
 */
static int wait_done_impl(uint32_t timeout_ms, echo_now_ms_fn now_ms,
                          int require_new, uint32_t count_before)
{
    if (timeout_ms == 0u || now_ms == NULL)
        return -1;

    const uint64_t started = now_ms();
    for (uint32_t poll = 0u; poll < ECHO_MAX_POLLS; ++poll) {
        struct echo_status s;
        if (echo_get_status(&s) != 0)
            return -2;
        const uint32_t flags = s.raw;

        if (s.last_error != 0u)
            return -10;
        if ((flags & ECHO_STATUS_START_REJECTED) != 0u)
            return -4;
        if ((flags & (ECHO_STATUS_CLIP | ECHO_STATUS_AVG_OVERFLOW |
                      ECHO_STATUS_CORR_OVERFLOW | ECHO_FRAME_ERROR)) != 0u)
            return -5;
        if ((flags & ECHO_STATUS_DONE) != 0u &&
            (flags & (ECHO_STATUS_BUSY | ECHO_STATUS_ACQ_BUSY)) == 0u) {
            if ((flags & ECHO_STATUS_START_ACCEPTED) == 0u)
                return -8;
            if (require_new) {
                uint32_t current = 0u;
                if (echo_get_transaction_count(&current) != 0)
                    return -2;
                if (current != (uint32_t)(count_before + 1u)) {
                    if (current != count_before)
                        return -11;
                    /* Old DONE/ACCEPTED: wait for a fresh completion. */
                    goto check_timeout;
                }
            }
            const uint32_t count =
                (flags & ECHO_STATUS_RESULT_MASK) >> ECHO_STATUS_RESULT_SHIFT;
            uint32_t frames = 0u;
            if (echo_get_frame_count(&frames) != 0)
                return -2;
            return count == ECHO_EXPECTED_RESULTS && frames == 32u ? 0 : -6;
        }
check_timeout:
        if ((uint64_t)(now_ms() - started) >= (uint64_t)timeout_ms)
            return -3;
    }
    return -3;
}

int echo_wait_done(uint32_t timeout_ms, echo_now_ms_fn now_ms)
{
    return wait_done_impl(timeout_ms, now_ms, 0, 0u);
}

/* One-shot measurement; the caller must load and commit both coeff banks. */
int echo_run_transaction_traced(uint32_t timeout_ms, echo_now_ms_fn now_ms,
                                echo_transaction_trace_t *trace)
{
    if (trace != NULL) {
        trace->tx_on_entry = UINT32_MAX;
        trace->tx_after_clear = UINT32_MAX;
        trace->tx_on_completion = UINT32_MAX;
    }
    if (timeout_ms == 0u || now_ms == NULL)
        return -1;

    struct echo_status s;
    if (echo_get_status(&s) != 0)
        return -2;
    if (s.last_error != 0u)
        return -10;
    if ((s.raw & (ECHO_STATUS_COEFF_VALID | ECHO_STATUS_ADC_READY)) !=
        (ECHO_STATUS_COEFF_VALID | ECHO_STATUS_ADC_READY) ||
        (s.raw & (ECHO_STATUS_BUSY | ECHO_STATUS_ACQ_BUSY)) != 0u)
        return -7;

    /* Record entry count for diagnosing cumulative-vs-resettable counters. */
    uint32_t tx_entry = 0u;
    if (echo_get_transaction_count(&tx_entry) != 0)
        return -2;
    if (trace != NULL)
        trace->tx_on_entry = tx_entry;
    if (echo_clear_status() != 0)
        return -2;

    /* The clear pulse is generated by the AXI bridge. Do not issue START
     * against stale DONE/ACCEPTED sticky flags from a prior transaction. */
    int cleared = 0;
    for (uint32_t poll = 0u; poll < ECHO_CLEAR_MAX_POLLS; ++poll) {
        if (echo_get_status(&s) != 0)
            return -2;
        if (s.last_error != 0u)
            return -10;
        if ((s.raw & (ECHO_STATUS_DONE | ECHO_STATUS_START_ACCEPTED |
                      ECHO_STATUS_START_REJECTED)) == 0u) {
            cleared = 1;
            break;
        }
    }
    if (!cleared)
        return -9;

    if (s.last_error != 0u)
        return -10;
    if ((s.raw & (ECHO_STATUS_COEFF_VALID | ECHO_STATUS_ADC_READY)) !=
        (ECHO_STATUS_COEFF_VALID | ECHO_STATUS_ADC_READY) ||
        (s.raw & (ECHO_STATUS_BUSY | ECHO_STATUS_ACQ_BUSY)) != 0u)
        return -7;
    /* Snapshot before START so a previous run cannot masquerade as success. */
    uint32_t tx_before = 0u;
    if (echo_get_transaction_count(&tx_before) != 0)
        return -2;
    if (trace != NULL)
        trace->tx_after_clear = tx_before;
    if (echo_start() != 0)
        return -2;
    int rc = wait_done_impl(timeout_ms, now_ms, 1, tx_before);
    if (trace != NULL) {
        uint32_t value;
        if (echo_get_transaction_count(&value) == 0)
            trace->tx_on_completion = value;
    }
    return rc;
}

int echo_run_transaction(uint32_t timeout_ms, echo_now_ms_fn now_ms)
{
    return echo_run_transaction_traced(timeout_ms, now_ms, NULL);
}
